%% =======================================================
%% 1. Z轴 (高度) 齐次 PI 控制器 (HPIC) 参数计算 (2维)
%% =======================================================
% 使用你真实物理模型的质量 (请根据实际情况修改，这里用你提供的 1.4kg)
m = 1.4; 

% 1.1 物理模型状态空间 (状态: 高度误差z, 垂直速度误差vz)
A_z = [0, 1; 
       0, 0];
B_z = [0; 
       1/m];

% 1.2 线性 PID 增益 (来自原厂控制器 Z 轴增益)
K_z_lin = [-5, -2]; 
Ki_z_lin = [-0.1, 0]; % 积分项，仅对高度误差积分

% 1.3 调用积分升级工具计算齐次结构矩阵与 P 矩阵
disp('-> 正在计算 Z 轴...');
[K0_z, G0_z, P_z, Ki_new_z, mu_min_z, mu_max_z] = lpic2hpic(A_z, B_z, K_z_lin, Ki_z_lin);

% 1.4 设定齐次度与计算扩张矩阵
mu_z = -0.5; 
Gd_z = eye(2) + mu_z * G0_z;

% 1.5 计算非线性核心比例增益
K_z_nl = K_z_lin - K0_z; 

disp('✅ Z   轴 (2维 HPIC) 参数计算完成！(积分增益已重构为 Ki_new_z)');


%% =======================================================
%% 2. Yaw轴 (偏航) 齐次控制器 HPC 参数计算 (2维)
%% =======================================================
% 使用你真实物理模型的 Z 轴转动惯量
Izz = 0.0366;

% 2.1 物理模型状态空间 (状态: 偏航角, 偏航角速度)
A_yaw = [0, 1; 
         0, 0];
B_yaw = [0; 
         1/Izz];

% 2.2 线性 PD 增益 
K_yaw_lin = [-0.39, -0.21]; 

% 2.3 调用工具箱计算齐次参数
disp('-> 正在计算 Yaw 轴...');
[K0_yaw, G0_yaw, P_yaw, mu_min_yaw, mu_max_yaw] = lpc2hpc(A_yaw, B_yaw, K_yaw_lin);

% 2.4 设定齐次度与计算扩张矩阵 Gd
mu_yaw = -0.5; 
Gd_yaw = eye(2) + mu_yaw * G0_yaw;
K_yaw_nl = K_yaw_lin - K0_yaw;

disp('✅ Yaw 轴 (2维 HPC)  参数计算完成！');


%% =======================================================
%% 3. XY轴 (水平位置与姿态) 齐次控制器 HPC 参数计算 (8维)
%% =======================================================
g = 9.8;
Ixx = 0.0211; % 你坚持的真实物理参数
Iyy = 0.0219; % 你坚持的真实物理参数

% 3.1 构造 8x8 物理模型矩阵 A_xy
% 状态向量顺序: [x, y, x_dot, y_dot, theta, phi, theta_dot, phi_dot]^T
A_xy = zeros(8,8);
A_xy(1:2, 3:4) = eye(2);      
A_xy(3:4, 5:6) = g * eye(2);  
A_xy(5:6, 7:8) = eye(2);      

% 3.2 构造 8x2 控制输入矩阵 B_xy (使用你的真实惯量)
B_xy = zeros(8,2);
B_xy(7,1) = 1/Iyy;            
B_xy(8,2) = 1/Ixx;            

% 3.3 [新增核心步骤]：使用 LQR 为你的真实惯量重新计算 K 矩阵
% 既然质量惯量变了，原来的 K 矩阵就不能用了，我们重新解算一个极点分配
% Q 矩阵权重设计：重点关注位置误差和姿态阻尼
Q_xy = diag([10, 10, 5, 5, 2, 2, 0.1, 0.1]); 
% R 矩阵权重设计：限制电机推力不要过猛
R_xy = diag([1, 1]); 

% 重新计算专属于你机型的线性增益 K_xy_lin
disp('-> 正在通过 LQR 重新计算适配真实惯量的 K 矩阵...');
K_xy_lin = -lqr(A_xy, B_xy, Q_xy, R_xy);

% 注意：现在不要再加 TUNING_FACTOR 削弱补丁了，因为这个 K 是为你量身定做的！

% 3.4 调用工具箱计算 8维 齐次参数
disp('-> 正在计算 XY 轴齐次参数 (新 K 矩阵保证稳定裕度充足)...');
[K0_xy, G0_xy, P_xy, mu_min_xy, mu_max_xy] = lpc2hpc(A_xy, B_xy, K_xy_lin);

% 3.5 设定齐次度 
mu_xy = -1;

% 3.6 计算扩张矩阵 Gd
Gd_xy = eye(8) + mu_xy * G0_xy;
K_xy_nl = K_xy_lin - K0_xy;

disp('✅ XY  轴 (8维 HPC)  参数计算完成！');

